t = (10, 20, 30, 20, 40)

print("Tuple:", t)

print("Length:", len(t))
print("Count of 20:", t.count(20))
print("Index of 30:", t.index(30))

print("Maximum:", max(t))
print("Minimum:", min(t))
print("Sum:", sum(t))

print("Reversed:", tuple(reversed(t)))

print("Sorted:", tuple(sorted(t)))